"""Build Android string resources from i18n/*.json. Run: python tools/i18n.py

  i18n/ui.en.json     English source  -> res/values/strings.xml (default)
  i18n/ui.ta.json     Tamil, filled by translator -> res/values-ta/strings.xml
                      (missing keys fall back to English at runtime)
  i18n/ui.fixed.json  never translated (language names) -> res/values, translatable="false"

Placeholders are written {name} so translators / Google Translate don't mangle %1$s.
They become positional %N$s args numbered by first appearance in the ENGLISH string,
so Tamil can reorder them freely. Arg order is noted above each string in the XML.
"""
import json
import re
import sys
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
I18N = ROOT / "i18n"
RES = ROOT / "app/src/main/res"
PH = re.compile(r"\{(\w+)\}")


def arg_order(s):
    return {name: i + 1 for i, name in enumerate(dict.fromkeys(PH.findall(s)))}


def to_android(s, order):
    if order:
        s = s.replace("%", "%%")  # literal % must be escaped only in formatted strings
    s = escape(s).replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if s[:1] in ("@", "?"):
        s = "\\" + s
    return PH.sub(lambda m: f"%{order[m.group(1)]}$s", s)


def write(path, entries):
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             "<!-- GENERATED by tools/i18n.py from i18n/*.json. Edit the JSON, not this file. -->",
             "<resources>"]
    for key, value, order, attrs in entries:
        if order:
            lines.append(f"    <!-- args: {', '.join(order)} -->")
        lines.append(f'    <string name="{key}"{attrs}>{to_android(value, order)}</string>')
    lines.append("</resources>")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def load(name):
    p = I18N / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def main():
    en, fixed, ta = load("ui.en.json"), load("ui.fixed.json") or {}, load("ui.ta.json")
    orders = {k: arg_order(v) for k, v in en.items()}

    write(RES / "values/strings.xml",
          [(k, v, orders[k], "") for k, v in en.items()] +
          [(k, v, {}, ' translatable="false"') for k, v in fixed.items()])

    if ta is None:
        return
    errors = [f"unknown key in ui.ta.json: {k}" for k in ta if k not in en]
    errors += [f"{k}: placeholders {sorted(set(PH.findall(v)))} != English {sorted(orders[k])}"
               for k, v in ta.items() if k in en and set(PH.findall(v)) != set(orders[k])]
    if errors:
        sys.exit("ui.ta.json problems:\n  " + "\n  ".join(errors))
    write(RES / "values-ta/strings.xml", [(k, v, orders[k], "") for k, v in ta.items() if v.strip()])
    missing = [k for k in en if not ta.get(k, "").strip()]
    print(f"Tamil: {len(en) - len(missing)}/{len(en)} strings translated")


def _selftest():
    assert to_android("{n}% it's", arg_order("{n}% it's")) == "%1$s%% it\\'s"
    assert to_android("100% <ok> & \"x\"", {}) == "100% &lt;ok&gt; &amp; \\\"x\\\""
    assert to_android("{b} then {a}", {"a": 1, "b": 2}) == "%2$s then %1$s"  # reordered translation
    assert to_android("@home", {}) == "\\@home"


if __name__ == "__main__":
    _selftest()
    main()
