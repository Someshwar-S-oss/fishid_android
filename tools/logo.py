"""Build the FishID mark from assets/1506878692.svg (an angelfish). Run: python tools/logo.py

The mark is the fish in one colour with its bars cut through in the background colour (brand teal),
so it reads as a fish even at launcher size. Writes:
  app/src/main/res/drawable/ic_launcher_foreground.xml   adaptive-icon foreground (white fish, teal bars)
  app/src/main/res/drawable/ic_launcher_monochrome.xml   themed-icon layer: the plain silhouette
  app/src/main/res/mipmap-*/ic_launcher(_round).png      bitmaps for Android 7 (no adaptive icons), via headless Edge/Chrome
  src/fishMark.ts                                         the same paths for the in-app <Logo>
"""
import os
import re
import shutil
import subprocess
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'assets/1506878692.svg'
RES = ROOT / 'app/src/main/res'
TEAL, WHITE = '#0E6E7E', '#FFFFFF'
W, H = 411, 675  # the SVG's own size
FISH_HEIGHT = 0.94  # share of the visible icon the fish fills
CENTRE_X = W / 2  # the whole fish, streamers included, sits centred (the drawing fills the SVG edge to edge)

# The source colours: these make up the fish's body, fins and eye...
BODY = {'#F2F2D9', '#66B3B3', '#D9D9BF', '#FFFF00', '#87FFFF', '#004040', '#4D8080'}
# ...and the rest (lime bars, dark fin rays, black pupil) is cut out in the background colour.


def paths():
    svg = SRC.read_text(encoding='utf8')
    for m in re.finditer(r'<path([^>]*)/>', svg, re.S):
        a = m.group(1)
        fill = re.search(r'fill="([^"]*)"', a)
        d = re.search(r'd="([^"]*)"', a, re.S).group(1)
        yield (fill.group(1).upper() if fill else '#000000') in BODY, clean(d)


def clean(d):
    """Re-serialise path data with numbers rounded to 0.1 and explicit separators (Android's parser is strict)."""
    out = []
    for cmd, args in re.findall(r'([A-Za-z])([^A-Za-z]*)', d):
        nums = re.findall(r'-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?', args)
        out.append(cmd + ' '.join(f'{round(float(n), 1):g}' for n in nums))
    return ''.join(out)


def view():
    """The square of fish space that shows inside the icon's visible area: (x0, y0, side)."""
    side = H / FISH_HEIGHT
    return CENTRE_X - side / 2, (H - side) / 2, side


def vector(parts, body_colour, cut_colour):
    # Adaptive icons draw 108dp, of which the middle 72dp is visible; map the view square onto that.
    x0, y0, side = view()
    s = 72 / side
    body = '\n'.join(
        f'        <path android:fillColor="{body_colour if is_body else cut_colour}" android:pathData="{d}" />'
        for is_body, d in parts if is_body or cut_colour)
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/logo.py from assets/1506878692.svg. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <group android:scaleX="{s:.5f}" android:scaleY="{s:.5f}" android:translateX="{18 - x0 * s:.3f}" android:translateY="{18 - y0 * s:.3f}">
{body}
    </group>
</vector>
'''


def svg_markup(parts, size, round_shape):
    x0, y0, side = view()
    radius = size / 2 if round_shape else size * 0.22
    fish = ''.join(f'<path fill="{WHITE if b else TEAL}" d="{d}"/>' for b, d in parts)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 {size} {size}">'
            f'<rect width="{size}" height="{size}" rx="{radius}" fill="{TEAL}"/>'
            f'<svg width="{size}" height="{size}" viewBox="{x0:.1f} {y0:.1f} {side:.1f} {side:.1f}">{fish}</svg></svg>')


def browser():
    for p in (r'C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe', r'C:\Program Files\Google\Chrome\Application\chrome.exe'):
        if os.path.exists(p):
            return p
    return shutil.which('msedge') or shutil.which('chrome') or shutil.which('google-chrome')


def bitmaps(parts):
    exe = browser()
    if not exe:
        print('No Edge/Chrome found: Android 7 bitmaps not updated.')
        return
    densities = {'mdpi': 48, 'hdpi': 72, 'xhdpi': 96, 'xxhdpi': 144, 'xxxhdpi': 192}
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
        for dens, px in densities.items():
            for name, round_shape in (('ic_launcher', False), ('ic_launcher_round', True)):
                page = Path(tmp) / f'{name}_{dens}.html'
                page.write_text(f'<html><body style="margin:0;background:transparent">{svg_markup(parts, px, round_shape)}</body></html>', encoding='utf8')
                png = RES / f'mipmap-{dens}' / f'{name}.png'
                png.unlink(missing_ok=True)
                # Its own profile: otherwise an Edge already open on this PC may take the job and write nothing.
                subprocess.run([exe, '--headless=new', '--disable-gpu', '--hide-scrollbars', '--default-background-color=00000000',
                                f'--user-data-dir={Path(tmp) / "profile"}', f'--window-size={px},{px}', f'--screenshot={png}', page.as_uri()],
                               check=True, capture_output=True, timeout=60)
                # msedge.exe hands the work to a child process and returns at once: wait for the file.
                for _ in range(100):
                    if png.exists() and png.stat().st_size:
                        break
                    time.sleep(0.2)
                else:
                    raise SystemExit(f'Browser wrote no {png}; the old icons for the rest are left in place.')
                (RES / f'mipmap-{dens}' / f'{name}.webp').unlink(missing_ok=True)  # replaced by the PNG
    print('Android 7 bitmaps written.')


def main():
    parts = list(paths())
    (RES / 'drawable/ic_launcher_foreground.xml').write_text(vector(parts, WHITE, TEAL), encoding='utf8')
    (RES / 'drawable/ic_launcher_monochrome.xml').write_text(vector(parts, WHITE, None), encoding='utf8')
    x0, y0, side = view()
    rows = ',\n'.join(f"  [{'true' if b else 'false'}, '{d}']" for b, d in parts)
    (ROOT / 'src/fishMark.ts').write_text(
        '// Generated by tools/logo.py from assets/1506878692.svg. Do not edit by hand.\n'
        '// The FishID mark: [is part of the fish body, path]. Body paths take the fish colour, the rest the background.\n'
        f"export const markViewBox = '{x0:.1f} {y0:.1f} {side:.1f} {side:.1f}';\n"
        f'export const markPaths: [boolean, string][] = [\n{rows},\n];\n', encoding='utf8')
    bitmaps(parts)
    print(f'{len(parts)} paths')


if __name__ == '__main__':
    main()
